#!/usr/bin/env python3
"""Generate every T3 Craft credits file from credits/credits.json.

Run from anywhere with the standard library only:

    python3 -I credits/generate.py            # validate, then write all outputs
    python3 -I credits/generate.py --check    # validate and fail if outputs are stale (CI)

Options:
    --repo DIR      repository root to scan (default: the parent of this script's folder)
    --out DIR       where to write outputs (default: --repo)
    --modpack DIR   modpack source to read .pw.toml files from (default: <repo>/modpack)
    --ingest FILE[=PREFIX]   extra schematic credits file (repeatable); PREFIX is the
                             repo path the listed files live under

Outputs (paths relative to --out):
    CREDITS.md
    THIRD_PARTY_LICENSES.md
    modpack/CREDITS.md
    src/main/resources/assets/t3craft/credits.json   (read by the in-game Credits screen)
    <dir>/ATTRIBUTION.md   next to every bundled font and schematic

Exit status: 0 ok, 1 validation errors or gaps, 2 outputs stale (--check only).
"""
