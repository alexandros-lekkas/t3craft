# ---------------------------------------------------------------- helpers

def glob_re(pattern: str) -> re.Pattern:
    """Translate a repo glob (supports **, *, ?) to a regex over posix paths."""
    out, i = [], 0
    while i < len(pattern):
        c = pattern[i]
        if pattern.startswith("**/", i):
            out.append("(?:.*/)?"); i += 3
        elif pattern.startswith("**", i):
            out.append(".*"); i += 2
        elif c == "*":
            out.append("[^/]*"); i += 1
        elif c == "?":
            out.append("[^/]"); i += 1
        else:
            out.append(re.escape(c)); i += 1
    return re.compile("^" + "".join(out) + "$")


def license_name(spdx: str) -> str:
    return LICENSE_NAMES.get(spdx, spdx)


def license_url(entry: dict) -> str:
    if entry.get("license_url"):
        return entry["license_url"]
    spdx = entry["license"]
    if spdx in CC_URLS:
        return CC_URLS[spdx]
    if spdx.startswith("LicenseRef-"):
        return ""
    return f"https://spdx.org/licenses/{spdx}.html"


def md_link(text: str, url: str | None) -> str:
    return f"[{text}]({url})" if url else text


def md_escape_cell(s: str) -> str:
    return s.replace("|", "\\|").replace("\n", " ")


class Problems:
    def __init__(self):
        self.errors: list[str] = []
        self.warnings: list[str] = []
        self.info: list[str] = []

    def error(self, msg): self.errors.append(msg)
    def warn(self, msg): self.warnings.append(msg)
    def note(self, msg): self.info.append(msg)


# ---------------------------------------------------------------- loading

def list_files(root: Path) -> list[str]:
    files = []
    skip_dirs = {".git", ".gradle", "build", "run", "node_modules", ".venv", "venv", "__pycache__", ".idea"}
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if d not in skip_dirs)
        for f in sorted(filenames):
            files.append(Path(dirpath, f).relative_to(root).as_posix())
    return files


def first(d: dict, *keys):
    for k in keys:
        v = d.get(k)
        if v not in (None, "", []):
            return v
    return None


def slug(s: str) -> str:
    return re.sub(r"[^\w\- ]", "", s.lower()).replace(" ", "-") or "item"


def ingest(path: Path, cfg: dict, p: Problems) -> list[dict]:
    """Read a schematic credits file written by another tool. Tolerant of field names."""
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except Exception as e:  # noqa: BLE001
        p.error(f"{path}: cannot parse ({e})")
        return []
    items = data
    if isinstance(data, dict):
        items = first(data, "schematics", "entries", "credits", "builds", "items") or []
        if not items and "title" in data:
            items = [data]
    if not isinstance(items, list):
        p.error(f"{path}: expected a list of credits")
        return []
    prefix = cfg.get("files_prefix", "")
    out = []
    for n, it in enumerate(items):
        if not isinstance(it, dict):
            p.error(f"{path}[{n}]: not an object"); continue
        title = first(it, "title", "name")
        files = first(it, "files", "paths", "file", "path") or []
        if isinstance(files, str):
            files = [files]
        files = [f if f.startswith(("src/", "**")) else prefix + f.lstrip("./") for f in files]
        author = first(it, "author", "authors", "creator", "by", "builder")
        if isinstance(author, list):
            author = ", ".join(author)
        e = {
            "id": "schem-" + slug(str(first(it, "id", "slug") or title or n)),
            "kind": it.get("kind", cfg.get("kind", "schematic")),
            "title": title,
            "author": author,
            "url": first(it, "url", "source_url", "source", "link"),
            "license": first(it, "license", "spdx", "license_id"),
            "license_url": first(it, "license_url", "licence_url"),
            "copyright": it.get("copyright"),
            "files": files,
            "modifications": first(it, "modifications", "changes", "modified"),
            "where_used": first(it, "where_used", "used_in", "usage") or cfg.get("where_used"),
            "permission": it.get("permission"),
            "status": "bundled",
            "_ingested_from": str(path),
        }
        out.append({k: v for k, v in e.items() if v not in (None, "", [])})
    p.note(f"ingested {len(out)} credit(s) from {path}")
    return out


def parse_pw_toml(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    if tomllib:
        return tomllib.loads(text)
    out = {}
    for line in text.splitlines():  # minimal fallback: top-level key = "value"
        m = re.match(r'^(\w[\w-]*)\s*=\s*"(.*)"\s*$', line)
        if m:
            out[m.group(1)] = m.group(2)
        if line.startswith("["):
            break
    return out


