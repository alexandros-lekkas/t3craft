class Credits:
    def __init__(self, args):
        self.repo = Path(args.repo).resolve()
        self.out = Path(args.out).resolve() if args.out else self.repo
        self.p = Problems()
        self.cfg = json.loads((HERE / "credits.json").read_text(encoding="utf-8"))
        md = self.cfg.get("modpack", {})
        self.modpack = Path(args.modpack).resolve() if args.modpack else self.repo / md.get("dir", "modpack")
        # A pack is only "present" when its packwiz metadata is; a folder holding just the
        # generated CREDITS.md doesn't count.
        self.has_pack = (self.modpack / "pack.toml").is_file()
        # Generated documents must never activate a credit or match a directory glob.
        # Keep list_files unfiltered: stale attribution cleanup still needs to see them.
        generated = {"CREDITS.md", "THIRD_PARTY_LICENSES.md", "modpack/CREDITS.md", CREDITS_JSON_OUT}
        self.files = [f for f in list_files(self.repo)
                      if f not in generated and Path(f).name != "ATTRIBUTION.md"]
        self.entries: list[dict] = list(self.cfg.get("credits", []))
        for ing in self.cfg.get("ingest", []):
            src = self.repo / ing["path"]
            if src.exists():
                self.entries += ingest(src, ing, self.p)
            else:
                self.p.note(f"ingest source not present yet: {ing['path']}")
        for spec in args.ingest or []:
            path, _, prefix = spec.partition("=")
            self.entries += ingest(Path(path), {"kind": "schematic", "files_prefix": prefix}, self.p)

    # -- validation
    def validate(self):
        seen = set()
        for e in self.entries:
            where = e.get("_ingested_from") or "credits.json"
            eid = e.get("id", "?")
            for k in REQUIRED:
                if not e.get(k):
                    self.p.error(f"{where}: '{eid}' is missing '{k}'"
                                 + (" (license unknown: find it or get written permission)" if k == "license" else ""))
            for k in e:
                if k not in KNOWN_FIELDS:
                    self.p.warn(f"{where}: '{eid}' has unknown field '{k}'")
            if eid in seen:
                self.p.error(f"duplicate id '{eid}'")
            seen.add(eid)
            if not ID_RE.match(eid):
                self.p.error(f"'{eid}': id must be lowercase kebab-case")
            if e.get("kind") not in KINDS:
                self.p.error(f"'{eid}': kind '{e.get('kind')}' not one of {KINDS}")
            e.setdefault("status", "bundled" if e.get("files") else "referenced")
            if e["status"] not in STATUSES:
                self.p.error(f"'{eid}': status must be one of {sorted(STATUSES)}")
            if not e.get("original") and not e.get("url") and e.get("kind") not in ("trademark",):
                self.p.error(f"'{eid}': third-party credit needs a 'url'")
            if e.get("kind") == "mod" and not e.get("modpack_file"):
                self.p.error(f"'{eid}': mods need 'modpack_file'")
            if not isinstance(e.get("files", []), list):
                self.p.error(f"'{eid}': 'files' must be a list of globs")
            e["_matched"] = self.match(e)
            e["_active"] = self.is_active(e)

        for e in self.active():
            lic = e.get("license") or ""
            if e["status"] == "bundled" and not e.get("original"):
                if lic and lic not in REDISTRIBUTABLE and not e.get("permission"):
                    self.p.error(f"'{e['id']}': bundled under '{lic}', which does not allow redistribution. "
                                 "Remove the files, or add 'permission' (link to written permission).")
                if lic in NONCOMMERCIAL:
                    self.p.warn(f"'{e['id']}': {lic} is non-commercial; T3 Craft must stay free to ship it.")
                if lic.startswith("CC-BY") and not e.get("modifications"):
                    self.p.warn(f"'{e['id']}': CC BY requires saying whether it was changed; add 'modifications'.")
                if lic in REDISTRIBUTABLE and not lic.startswith("LicenseRef-") and not (HERE / "licenses" / f"{lic}.txt").exists():
                    self.p.error(f"'{e['id']}': no license text at credits/licenses/{lic}.txt")
                if lic in ("MIT", "BSD-3-Clause", "BSD-2-Clause", "OFL-1.1") and not e.get("copyright"):
                    self.p.error(f"'{e['id']}': {lic} needs the original 'copyright' line")

    def match(self, e) -> list[str]:
        pats = [glob_re(g) for g in e.get("files", [])]
        return [f for f in self.files if any(r.match(f) for r in pats)]

    def is_active(self, e) -> bool:
        if e.get("modpack_file"):
            if not self.has_pack:
                return True  # no pack to compare against: keep listing it
            return (self.modpack / e["modpack_file"]).exists()
        cond = e.get("active_if")
        if cond:
            g = cond.get("grep")
            if g:
                r = glob_re(g["files"])
                for f in self.files:
                    if r.match(f):
                        try:
                            if g["text"] in (self.repo / f).read_text(encoding="utf-8", errors="ignore"):
                                return True
                        except OSError:
                            pass
                return False
            ex = cond.get("exists")
            if ex:
                r = glob_re(ex)
                return any(r.match(f) for f in self.files)
            self.p.error(f"'{e['id']}': unknown active_if {cond}")
            return False
        if e.get("files") and e["status"] == "bundled" and not e.get("always"):
            return bool(e["_matched"])
        return True

    def active(self):
        return [e for e in self.entries if e.get("_active")]

    # -- coverage
    def coverage(self):
        cov = self.cfg.get("coverage", {})
        roots = [r.rstrip("/") + "/" for r in cov.get("roots", [])]
        ignore = [glob_re(g) for g in cov.get("ignore", [])]
        covered = set()
        for e in self.entries:
            covered.update(e.get("_matched", []))
        uncovered = []
        for f in self.files:
            if not any(f.startswith(r) for r in roots):
                continue
            if any(r.match(f) for r in ignore):
                continue
            if f not in covered:
                uncovered.append(f)
        for f in uncovered:
            self.p.error(f"uncovered asset: {f} (add it to a credit's 'files' or to an original-work entry)")
        # every pack project needs a credit
        if self.has_pack:
            want = {e["modpack_file"] for e in self.entries if e.get("modpack_file")}
            for pat in self.cfg.get("modpack", {}).get("patterns", []):
                r = glob_re(pat)
                for f in list_files(self.modpack):
                    if r.match(f) and f not in want:
                        self.p.error(f"modpack project without a credit: {f}")
            for e in self.entries:
                if e.get("modpack_file") and not e["_active"]:
                    self.p.note(f"'{e['id']}' not in the pack any more ({e['modpack_file']} missing): omitted")
                elif e.get("modpack_file"):
                    meta = parse_pw_toml(self.modpack / e["modpack_file"])
                    e["_filename"] = meta.get("filename")
        else:
            self.p.note(f"no packwiz pack at {self.modpack}; listing every mod in credits.json")
        for e in self.entries:
            if not e["_active"] and not e.get("modpack_file"):
                self.p.note(f"'{e['id']}' dormant (its files/condition are not in the repo yet): omitted")
        return uncovered

    # ------------------------------------------------------------ renderers
    def grouped(self, include_mods=True):
        groups = []
        for k in SECTION_ORDER:
            if k == "mod" and not include_mods:
                continue
            items = [e for e in self.active() if e["kind"] == k]
            if items:
                groups.append((k, items))
        return groups

    def lic_md(self, e):
        return md_link(license_name(e["license"]), license_url(e))

    def render_credits_md(self) -> str:
        c = self.cfg
        L = [f"<!-- {GEN_NOTE} -->", "", "# Credits", ""]
        L += [f"{c['project']['name']} exists because of other people's work. This page lists every project, "
              "font, build, mod and name it uses, who made it, and the license it comes under. "
              f"The mod itself is [MIT]({c['project']['repo']}/blob/main/LICENSE).", ""]
        up = next((e for e in self.active() if e["id"] == "upstream-t3craft"), None)
        if up:
            L += [f"> **Built on {md_link('maxwellyoung/t3craft', up['url'])} by {up['author']}.** "
                  f"{up['where_used']}", ""]
        groups = self.grouped()
        L += ["**Contents:** " + " · ".join(f"[{KIND_TITLES[k]}](#{slug(KIND_TITLES[k])})" for k, _ in groups)
              + " · [Disclaimers](#disclaimers)", ""]
        for k, items in groups:
            L += [f"## {KIND_TITLES[k]}", ""]
            if k == "mod":
                L += ["The [T3 Craft modpack](modpack/CREDITS.md) downloads these from Modrinth. "
                      "None of them are re-hosted or changed. Mod Menu lists them in game too.", "",
                      "| Mod | By | Version | License | Why it's in the pack |", "|---|---|---|---|---|"]
                for e in items:
                    L.append("| " + " | ".join(md_escape_cell(x) for x in [
                        md_link(e["title"], e["url"]), e["author"], f"`{e.get('version', '')}`",
                        self.lic_md(e), e["where_used"]]) + " |")
                L.append("")
                continue
            if k == "art" or k == "schematic":
                orig = [e for e in items if e.get("original")]
                third = [e for e in items if not e.get("original")]
                for e in third:
                    L += self.entry_block(e)
                if orig:
                    if third:
                        L += ["**Made for T3 Craft**", ""]
                    L += ["| Work | By | License | Where |", "|---|---|---|---|"]
                    for e in orig:
                        where = e["where_used"] + (f" *Inspired by: {e['inspired_by']}*" if e.get("inspired_by") else "")
                        L.append("| " + " | ".join(md_escape_cell(x) for x in [
                            e["title"], e["author"], self.lic_md(e), where]) + " |")
                    L.append("")
                continue
            for e in items:
                L += self.entry_block(e)
        L += ["## Disclaimers", ""]
        for key in ("minecraft", "t3", "providers"):
            if c["disclaimers"].get(key):
                L += [f"- {c['disclaimers'][key]}"]
        L += ["", "Full license texts for everything bundled are in [THIRD_PARTY_LICENSES.md](THIRD_PARTY_LICENSES.md). "
              "Found something missing or wrong? Open an issue and it gets fixed first.", ""]
        return "\n".join(L)

    def entry_block(self, e) -> list[str]:
        head = f"### {md_link(e['title'], e.get('url'))}"
        L = [head, "", f"**By** {e['author']} · **License** {self.lic_md(e)}"
             + (f" · **Version** `{e['version']}`" if e.get("version") else "")
             + (f" · [Source]({e['source']})" if e.get("source") and e.get("source") != e.get("url") else ""), ""]
        L.append(f"- **Used for:** {e['where_used']}")
        if e.get("modifications"):
            L.append(f"- **Changes:** {e['modifications']}")
        if e.get("inspired_by"):
            L.append(f"- **Inspired by:** {e['inspired_by']}")
        if e.get("notes"):
            L.append(f"- **Note:** {e['notes']}")
        if e.get("permission"):
            L.append(f"- **Permission:** {e['permission']}")
        if e["status"] == "bundled" and e.get("_matched") and e["kind"] in ("font", "schematic"):
            L.append("- **Files:** " + ", ".join(f"`{f}`" for f in e["_matched"][:6])
                     + (f" and {len(e['_matched']) - 6} more" if len(e["_matched"]) > 6 else ""))
        L.append("")
        return L

    def render_third_party(self) -> str:
        L = [f"<!-- {GEN_NOTE} -->", "", "# Third-party licenses", "",
             "Full license texts for third-party work that ships inside T3 Craft (the mod jar, this repository "
             "or the website). Projects that are only linked to, like the modpack's mods, keep their own "
             "licenses on their pages; see [CREDITS.md](CREDITS.md).", ""]
        bundled = [e for e in self.active() if e["status"] == "bundled"
                   and not e.get("original") and not e["license"].startswith("LicenseRef-")]
        # The project's own MIT notice (upstream + fork) is always reproduced.
        by_lic: dict[str, list[dict]] = {}
        for e in bundled:
            by_lic.setdefault(e["license"], []).append(e)
        if not by_lic:
            L += ["Nothing third-party is bundled right now.", ""]
        L += ["| License | Used by |", "|---|---|"]
        for lic in sorted(by_lic):
            L.append(f"| [{license_name(lic)}](#{slug(license_name(lic))}) | "
                     + ", ".join(e["title"] for e in by_lic[lic]) + " |")
        L.append("")
        for lic in sorted(by_lic):
            L += [f"## {license_name(lic)}", ""]
            for e in by_lic[lic]:
                L += [f"**{md_link(e['title'], e.get('url'))}**, {e['author']}"
                      + (f"<br>\n{e['copyright']}" if e.get("copyright") else ""), ""]
            text = (HERE / "licenses" / f"{lic}.txt").read_text(encoding="utf-8").strip()
            if lic in ("MIT", "BSD-3-Clause", "BSD-2-Clause"):
                # SPDX templates carry a placeholder copyright line; the real lines are listed above.
                text = re.sub(r"^Copyright \(c\) <year> <[^>]+>\.?[ \t]*$", "Copyright (c) <the holders listed above>",
                              text, flags=re.M)
            L += ["<details><summary>Full text</summary>", "", "```text", text, "```", "", "</details>", ""]
        return "\n".join(L)

    def render_modpack(self) -> str:
        mods = [e for e in self.active() if e["kind"] == "mod"]
        L = [f"<!-- {GEN_NOTE} -->", "", "# T3 Craft modpack credits", "",
             "Every project in the pack, who makes it and its license. The pack only points at Modrinth's CDN; "
             "no mod files are re-hosted, mirrored or modified. T3 Craft itself is credited in the "
             "[main CREDITS.md](https://github.com/alexandros-lekkas/t3craft/blob/main/CREDITS.md).", "",
             "| Project | By | Version | License |", "|---|---|---|---|"]
        for e in mods:
            L.append("| " + " | ".join(md_escape_cell(x) for x in [
                md_link(e["title"], e["url"]) + (f" ([source]({e['source']}))" if e.get("source") else ""),
                e["author"], f"`{e.get('version', '')}`", self.lic_md(e)]) + " |")
        L.append("")
        custom = [e for e in mods if e["license"].startswith("LicenseRef-")]
        if custom:
            L += ["## Custom licenses", ""]
            for e in custom:
                L.append(f"- **{e['title']}** uses the {self.lic_md(e)}. "
                         "It is not a general open-source grant: the pack links to the official download and never "
                         "mirrors or modifies it.")
            L.append("")
        lgpl = [e["title"] for e in mods if e["license"].startswith(("LGPL", "MPL"))]
        if lgpl:
            L += [f"LGPL and MPL projects ({', '.join(lgpl)}) are used unmodified; their source is linked above.", ""]
        L += ["## Disclaimer", "", self.cfg["disclaimers"]["minecraft"], ""]
        return "\n".join(L)

    def render_ingame(self) -> str:
        groups = []
        for k, items in self.grouped():
            groups.append({
                "kind": k,
                "title": KIND_TITLES[k],
                "entries": [
                    {k2: v for k2, v in {
                        "title": e["title"],
                        "author": e["author"],
                        "license": license_name(e["license"]),
                        "url": e.get("url") or e.get("source"),
                        "note": e["where_used"] if len(e["where_used"]) <= 120 else e["where_used"][:119].rstrip() + "…",
                        "version": e.get("version"),
                        "original": True if e.get("original") else None,
                    }.items() if v is not None}
                    for e in items if e.get("in_game", True)
                ],
            })
        doc = {
            "_generated": GEN_NOTE,
            "format": 1,
            "project": self.cfg["project"]["name"],
            "license": self.cfg["project"]["license"],
            "repo": self.cfg["project"]["repo"],
            "groups": groups,
            "disclaimers": [self.cfg["disclaimers"][k] for k in ("minecraft", "t3", "providers") if self.cfg["disclaimers"].get(k)],
        }
        return json.dumps(doc, indent=2, ensure_ascii=False) + "\n"

    def render_attributions(self) -> dict[str, str]:
        by_dir: dict[str, list[tuple[dict, list[str]]]] = {}
        for e in self.active():
            if e["kind"] not in ("font", "schematic") or e["status"] != "bundled" or e.get("original"):
                continue
            dirs: dict[str, list[str]] = {}
            for f in e["_matched"]:
                d = f.rsplit("/", 1)[0] if "/" in f else "."
                dirs.setdefault(d, []).append(f.rsplit("/", 1)[-1])
            for d, names in dirs.items():
                by_dir.setdefault(d, []).append((e, names))
        out = {}
        for d, items in sorted(by_dir.items()):
            L = [f"<!-- {GEN_NOTE} -->", "", "# Attribution", "",
                 "Third-party files in this folder. Keep this file next to them when copying.", ""]
            for e, names in items:
                L += [f"## {md_link(e['title'], e.get('url'))}", "",
                      f"- **By:** {e['author']}",
                      f"- **License:** {self.lic_md(e)}"]
                if e.get("copyright"):
                    L.append(f"- **Copyright:** {e['copyright']}")
                L.append(f"- **Changes:** {e.get('modifications') or 'None.'}")
                L.append("- **Files:** " + ", ".join(f"`{n}`" for n in names))
                L.append("")
            L += ["Full license texts: [THIRD_PARTY_LICENSES.md](" + "../" * (0 if d == "." else d.count("/") + 1)
                  + "THIRD_PARTY_LICENSES.md).", ""]
            out[(d + "/" if d != "." else "") + "ATTRIBUTION.md"] = "\n".join(L)
        return out

    def outputs(self) -> dict[str, str]:
        out = {
            "CREDITS.md": self.render_credits_md(),
            "THIRD_PARTY_LICENSES.md": self.render_third_party(),
            "modpack/CREDITS.md": self.render_modpack(),
            CREDITS_JSON_OUT: self.render_ingame(),
        }
        out.update(self.render_attributions())
        return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--repo", default=str(HERE.parent))
    ap.add_argument("--out")
    ap.add_argument("--modpack")
    ap.add_argument("--ingest", action="append")
    ap.add_argument("--check", action="store_true", help="validate and fail if outputs are stale; write nothing")
    ap.add_argument("--quiet", action="store_true")
    args = ap.parse_args(argv)

    c = Credits(args)
    c.validate()
    c.coverage()
    p = c.p
    say = (lambda *a: None) if args.quiet else print
    for m in p.info:
        say(f"  info: {m}")
    for m in p.warnings:
        print(f"  warn: {m}")
    for m in p.errors:
        print(f" ERROR: {m}")
    if p.errors:
        print(f"credits: {len(p.errors)} error(s); nothing written.")
        return 1

    outs = c.outputs()
    # Stale ATTRIBUTION.md files (folder no longer has third-party files) are reported too.
    stale_attr = [f for f in list_files(c.out) if f.endswith("ATTRIBUTION.md") and f not in outs
                  and GEN_NOTE in (c.out / f).read_text(encoding="utf-8", errors="ignore")]
    if args.check:
        stale = [rel for rel, text in outs.items()
                 if not (c.out / rel).exists() or (c.out / rel).read_text(encoding="utf-8") != text]
        stale += stale_attr
        if stale:
            for s in stale:
                print(f" STALE: {s}")
            print("credits: outputs are out of date. Run: python3 -I credits/generate.py")
            return 2
        say(f"credits: ok ({len(c.active())} credits, {len(outs)} outputs up to date)")
        return 0
    for rel, text in outs.items():
        dest = c.out / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        if not dest.exists() or dest.read_text(encoding="utf-8") != text:
            dest.write_text(text, encoding="utf-8")
            say(f" wrote {rel}")
    for f in stale_attr:
        (c.out / f).unlink()
        say(f" removed {f}")
    say(f"credits: ok ({len(c.active())} active credits, {len(outs)} outputs)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
